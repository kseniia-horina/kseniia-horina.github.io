// Copies the latin + latin-ext font subsets out of node_modules into assets/fonts
// and writes assets/css/fonts.css. Run with `npm run fonts` after updating packages.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outFonts = path.join(root, 'assets', 'fonts');
const outCss = path.join(root, 'assets', 'css', 'fonts.css');
const SUBSETS = ['latin', 'latin-ext'];

// [package dir, css files to read, family name to emit]
const SOURCES = [
  ['@fontsource/space-grotesk', ['400.css', '500.css', '700.css'], 'Space Grotesk'],
  ['@fontsource/ibm-plex-mono', ['400.css', '500.css'], 'IBM Plex Mono'],
  ['@fontsource-variable/source-serif-4', ['opsz.css'], 'Source Serif 4'],
];

fs.mkdirSync(outFonts, { recursive: true });
let css = '/* Generated by scripts/copy-fonts.js — do not edit by hand */\n';

for (const [pkg, files, family] of SOURCES) {
  const dir = path.join(root, 'node_modules', pkg);
  for (const file of files) {
    const src = fs.readFileSync(path.join(dir, file), 'utf8');
    const blocks = src.split('@font-face').slice(1);
    for (const block of blocks) {
      const m = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/);
      if (!m) continue;
      const fileName = m[1];
      if (!SUBSETS.some(s => fileName.includes(`-${s}-`))) continue;
      fs.copyFileSync(path.join(dir, 'files', fileName), path.join(outFonts, fileName));
      const body = block
        .replace(/font-family:[^;]+;/, `font-family: '${family}';`)
        .replace(/src:[^;]+;/, `src: url(../fonts/${fileName}) format('woff2');`)
        .replace(/\n\n\/\*[\s\S]*$/, '\n');
      css += '@font-face' + body.trimEnd() + '\n';
    }
  }
}

fs.writeFileSync(outCss, css);
console.log('Wrote', path.relative(root, outCss), 'and', fs.readdirSync(outFonts).length, 'font files');
